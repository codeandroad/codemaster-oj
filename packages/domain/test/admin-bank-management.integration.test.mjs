import test from 'node:test';
import assert from 'node:assert/strict';
import http from 'node:http';
import { randomBytes } from 'node:crypto';
import { createPool } from '../src/db.mjs';
import { migrate } from '../src/migrate.mjs';
import { bootstrap } from '../src/bootstrap.mjs';
import { createApp, loadConfig } from '../src/app.mjs';
import { SCHOOL_BANK } from '../src/library.mjs';

test('admin bank management covers private banks, safe problem archiving and reversible visibility without deleting grades',
 {skip:!process.env.TEST_DATABASE_URL,timeout:60000},async()=>{
  const manager=createPool(process.env.TEST_DATABASE_URL);
  const schema=`admin_bank_${randomBytes(6).toString('hex')}`;
  await manager.query(`CREATE SCHEMA ${schema}`);
  const connection=new URL(process.env.TEST_DATABASE_URL);
  connection.searchParams.set('options',`-csearch_path=${schema}`);
  const pool=createPool(connection.href);
  const password=randomBytes(24).toString('base64url');
  let server;
  try {
   await migrate(pool);
   await bootstrap(pool,{name:'管理员',number:'ADM-BANK',username:'bank-admin',password});
   server=http.createServer(await createApp(pool,loadConfig({SESSION_SECRET:randomBytes(48).toString('base64url'),APP_ORIGIN:'http://bank.test',COOKIE_SECURE:'false'})));
   await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
   const base=`http://127.0.0.1:${server.address().port}/api/v1`;
   const request=async(path,method='GET',body,auth)=>{
    const response=await fetch(`${base}${path}`,{method,headers:{Origin:'http://bank.test',...(body?{'Content-Type':'application/json'}:{}),...(auth?{Cookie:auth.cookie,'X-CSRF-Token':auth.csrfToken}:{})},...(body?{body:JSON.stringify(body)}:{})});
    const data=await response.json();
    return {status:response.status,data,cookie:response.headers.get('set-cookie')?.split(';')[0],csrfToken:data.csrfToken};
   };
   const admin=await request('/auth/login','POST',{username:'bank-admin',password});
   assert.equal(admin.status,200);
   const createAccount=async(kind,number,name,username)=>{
    const issued=await request('/people','POST',{kind,number,name},admin);
    assert.equal(issued.status,201);
    const registered=await request('/auth/register','POST',{kind,number,name,username,activationCode:issued.data.activationCode,password});
    assert.equal(registered.status,201);
    return registered;
   };
   const teacher=await createAccount('teacher','T-BANK','教师','bank-teacher');
   const student=await createAccount('student','S-BANK','学生','bank-student');
   const timedStudent=await createAccount('student','S-TIMED','训练学生','bank-timed-student');
   const adminId=(await pool.query("SELECT id FROM accounts WHERE username='bank-admin'")).rows[0].id;
   const privateBank=(await pool.query("INSERT INTO problem_banks(name,owner_account_id,visibility) VALUES('教师私有库',$1,'private') RETURNING id",[teacher.data.user.id])).rows[0].id;
   const schoolProblem=(await pool.query('INSERT INTO problems(owner_account_id,bank_id) VALUES($1,$2) RETURNING id',[adminId,SCHOOL_BANK])).rows[0].id;
   const version=(await pool.query(`INSERT INTO problem_versions(problem_id,title,mode,statement,time_limit_ms,memory_limit_mb,reference_code,validation_status,samples)
    VALUES($1,'安全归档题','stdio','输出 1',1000,64,'print(1)','AC',$2::jsonb) RETURNING id`,[schoolProblem,JSON.stringify([{name:'公开样例',input:'1\n',expected:'1\n',enabled:true}])])).rows[0].id;
   await pool.query("INSERT INTO test_cases(version_id,position,input,expected,weight,name,enabled) VALUES($1,0,'secret input','secret output',100,'正式测试',true)",[version]);
   await pool.query('UPDATE problem_versions SET published_at=now() WHERE id=$1',[version]);
   await pool.query('UPDATE problems SET current_version_id=$1 WHERE id=$2',[version,schoolProblem]);
   const approved=await request(`/problems/${schoolProblem}/rank-review`,'PATCH',{versionId:version,decision:'approved'},admin);
   assert.equal(approved.status,200,JSON.stringify(approved.data));
   const reviewDetail=await request(`/problems/${schoolProblem}?versionId=${version}`,'GET',undefined,admin);
   assert.equal(reviewDetail.status,200);
   assert.equal(reviewDetail.data.versionId,version,'review detail is pinned to the selected version');
   assert.equal(reviewDetail.data.statement,'输出 1');
   assert.equal(reviewDetail.data.samples[0].name,'公开样例');
   assert.equal(reviewDetail.data.tests[0].input,'secret input');
   assert.equal(reviewDetail.data.referenceCode,'print(1)');
   const studentDetail=await request(`/problems/${schoolProblem}?versionId=${version}`,'GET',undefined,student);
   assert.equal(studentDetail.status,200);
   assert.equal(studentDetail.data.referenceCode,undefined,'student review detail never includes reference solution');
   assert.equal(studentDetail.data.tests,undefined,'student review detail never includes formal tests');
   assert.equal((await request('/admin/problem-banks','GET',undefined,teacher)).status,403);
   assert.equal((await request(`/admin/problem-banks/${privateBank}/problems`,'GET',undefined,student)).status,403);
   assert.equal((await request(`/admin/problems/${schoolProblem}`,'PATCH',{archived:true},teacher)).status,403);
   const listed=await request('/admin/problem-banks','GET',undefined,admin);
   assert.equal(listed.status,200);
   assert.equal(listed.data.items.find(b=>b.id===privateBank).ownerName,'教师');
   assert.equal(listed.data.items.find(b=>b.id===SCHOOL_BANK).publicVersionCount,1);
   const problems=await request(`/admin/problem-banks/${SCHOOL_BANK}/problems?search=${encodeURIComponent('安全归档')}`,'GET',undefined,admin);
   assert.equal(problems.status,200,JSON.stringify(problems.data));
   assert.equal(problems.data.total,1);
   assert.equal(problems.data.items[0].id,schoolProblem);
   const classId=(await pool.query('INSERT INTO classes(name,owner_account_id) VALUES($1,$2) RETURNING id',['测试班',adminId])).rows[0].id;
   const assignment=(await pool.query('INSERT INTO assignments(title,class_id,owner_account_id,due_at) VALUES($1,$2,$3,now()+interval \'1 day\') RETURNING id',['保留作业',classId,adminId])).rows[0].id;
   await pool.query('INSERT INTO assignment_problems(assignment_id,problem_id,version_id,points,position) VALUES($1,$2,$3,100,0)',[assignment,schoolProblem,version]);
   await pool.query('INSERT INTO assignment_participants(assignment_id,identity_id) VALUES($1,$2)',[assignment,student.data.user.identityId]);
   assert.equal((await request(`/problems/${schoolProblem}?versionId=${version}`,'GET',undefined,student)).status,200);
   const course=(await pool.query("INSERT INTO learning_paths(owner_account_id,title,published_at) VALUES($1,'引用课程',now()) RETURNING id",[adminId])).rows[0].id;
   const chapter=(await pool.query("INSERT INTO learning_chapters(path_id,title,position) VALUES($1,'引用章节',0) RETURNING id",[course])).rows[0].id;
   await pool.query('INSERT INTO chapter_problems(chapter_id,problem_id,version_id,position) VALUES($1,$2,$3,0)',[chapter,schoolProblem,version]);
   const blocked=await request(`/admin/problems/${schoolProblem}`,'PATCH',{archived:true},admin);
   assert.equal(blocked.status,409,JSON.stringify(blocked.data));
   assert.equal(blocked.data.error.code,'PROBLEM_REFERENCED');
   assert.equal((await pool.query('SELECT archived_at FROM problems WHERE id=$1',[schoolProblem])).rows[0].archived_at,null);
   assert.equal((await pool.query('SELECT school_visible_at FROM problem_versions WHERE id=$1',[version])).rows[0].school_visible_at!==null,true);
   await pool.query('UPDATE learning_paths SET archived_at=now() WHERE id=$1',[course]);
   const practice=(await pool.query("INSERT INTO timed_practices(title,class_id,owner_account_id,starts_at,ends_at,duration_minutes) VALUES('引用训练',$1,$2,now(),now()+interval '1 day',30) RETURNING id",[classId,adminId])).rows[0].id;
   await pool.query('INSERT INTO timed_practice_problems(practice_id,problem_id,version_id,points,position) VALUES($1,$2,$3,100,0)',[practice,schoolProblem,version]);
   const timedOnlyProblem=(await pool.query('INSERT INTO problems(owner_account_id,bank_id) VALUES($1,$2) RETURNING id',[adminId,SCHOOL_BANK])).rows[0].id;
   const timedOnlyVersion=(await pool.query(`INSERT INTO problem_versions(problem_id,title,mode,statement,time_limit_ms,memory_limit_mb,reference_code,validation_status,published_at)
    VALUES($1,'训练历史题','stdio','输出 3',1000,64,'print(3)','AC',now()) RETURNING id`,[timedOnlyProblem])).rows[0].id;
   await pool.query('UPDATE problems SET current_version_id=$1 WHERE id=$2',[timedOnlyVersion,timedOnlyProblem]);
   await pool.query('INSERT INTO timed_practice_problems(practice_id,problem_id,version_id,points,position) VALUES($1,$2,$3,100,1)',[practice,timedOnlyProblem,timedOnlyVersion]);
   await pool.query('INSERT INTO timed_practice_participants(practice_id,identity_id) VALUES($1,$2)',[practice,timedStudent.data.user.identityId]);
   // Simulate an inconsistent imported draft with an attempt: archiving it
   // must never turn the selected student's fixed-version URL into a preview.
   await pool.query("INSERT INTO timed_attempts(practice_id,identity_id,account_id,started_at,deadline_at) VALUES($1,$2,$3,now(),now()+interval '30 minutes')",[practice,timedStudent.data.user.identityId,timedStudent.data.user.id]);
   assert.equal((await request(`/admin/problems/${schoolProblem}`,'PATCH',{archived:true},admin)).data.error.code,'PROBLEM_REFERENCED');
   await pool.query('UPDATE timed_practices SET archived_at=now(),state=\'Archived\' WHERE id=$1',[practice]);
   const archived=await request(`/admin/problems/${schoolProblem}`,'PATCH',{archived:true},admin);
   assert.equal(archived.status,200,JSON.stringify(archived.data));
   assert.equal(archived.data.archived,true);
   assert.equal((await request(`/admin/problems/${timedOnlyProblem}`,'PATCH',{archived:true},admin)).status,200);
   const history=await request(`/admin/problems/${schoolProblem}`,'GET',undefined,admin);
   assert.equal(history.status,200,JSON.stringify(history.data));
   assert.equal(history.data.versions[0].title,'安全归档题');
   assert.equal(history.data.versions[0].statement,'输出 1');
   assert.equal((await request(`/admin/problems/${schoolProblem}`,'GET',undefined,teacher)).status,403);
   const withdrawn=(await pool.query('SELECT rank_review_status,school_visible_at FROM problem_versions WHERE id=$1',[version])).rows[0];
   assert.equal(withdrawn.rank_review_status,'revoked');
   assert.equal(withdrawn.school_visible_at,null);
   assert.equal((await request(`/problems/${schoolProblem}?versionId=${version}`,'GET',undefined,student)).status,200,'assigned historical version remains available');
   assert.equal((await request(`/problems/${schoolProblem}?versionId=${version}`,'GET',undefined,timedStudent)).status,404,'unreleased archived timed draft stays hidden even with an anomalous attempt');
   assert.equal((await request(`/problems/${schoolProblem}?versionId=${version}`,'GET',undefined,teacher)).status,404,'unassigned teacher cannot read archived private history');
   await pool.query('INSERT INTO teacher_classes(class_id,account_id) VALUES($1,$2)',[classId,teacher.data.user.id]);
   const assignedTeacher=await request(`/problems/${schoolProblem}?versionId=${version}`,'GET',undefined,teacher);
   assert.equal(assignedTeacher.status,200,'class teacher can read archived assignment or practice version');
   assert.equal(assignedTeacher.data.referenceCode,undefined,'class teacher does not gain reference solution through historical access');
   assert.equal((await request(`/problems/${timedOnlyProblem}?versionId=${timedOnlyVersion}`,'GET',undefined,teacher)).status,200,'class teacher can inspect archived timed-only fixed version');
   assert.equal((await request(`/problems/${timedOnlyProblem}?versionId=${timedOnlyVersion}`,'GET',undefined,timedStudent)).status,404,'timed-only version stays hidden before release');
   await pool.query('UPDATE timed_practices SET results_published_at=now() WHERE id=$1',[practice]);
   const releasedTimed=await request(`/problems/${schoolProblem}?versionId=${version}`,'GET',undefined,timedStudent);
   assert.equal(releasedTimed.status,200,'timed participant can read exact version once results are released');
   assert.equal(releasedTimed.data.referenceCode,undefined,'student cannot read reference solution');
   assert.equal(releasedTimed.data.tests,undefined,'student cannot read hidden tests');
   assert.equal((await request(`/problems/${timedOnlyProblem}?versionId=${timedOnlyVersion}`,'GET',undefined,timedStudent)).status,200,'released timed-only version remains available to participant');
   const restored=await request(`/admin/problems/${schoolProblem}`,'PATCH',{archived:false},admin);
   assert.equal(restored.status,200);
   const stillWithdrawn=(await pool.query('SELECT rank_review_status,school_visible_at FROM problem_versions WHERE id=$1',[version])).rows[0];
   assert.equal(stillWithdrawn.rank_review_status,'revoked');
   assert.equal(stillWithdrawn.school_visible_at,null,'restore never reapproves school visibility');
   const audit=(await pool.query("SELECT action FROM audit_events WHERE resource_id=$1 ORDER BY id",[schoolProblem])).rows.map(event=>event.action);
   assert.ok(audit.includes('problem.archive')&&audit.includes('problem.restore'));
   const privateProblem=(await pool.query('INSERT INTO problems(owner_account_id,bank_id) VALUES($1,$2) RETURNING id',[teacher.data.user.id,privateBank])).rows[0].id;
   const privateVersion=(await pool.query(`INSERT INTO problem_versions(problem_id,title,mode,statement,time_limit_ms,memory_limit_mb,reference_code,validation_status,published_at)
    VALUES($1,'私有作业题','stdio','输出 2',1000,64,'print(2)','AC',now()) RETURNING id`,[privateProblem])).rows[0].id;
   await pool.query('UPDATE problems SET current_version_id=$1 WHERE id=$2',[privateVersion,privateProblem]);
   await pool.query('INSERT INTO assignment_problems(assignment_id,problem_id,version_id,points,position) VALUES($1,$2,$3,100,1)',[assignment,privateProblem,privateVersion]);
   assert.equal((await request(`/admin/problem-banks/${privateBank}/problems`,'GET',undefined,admin)).data.items[0].id,privateProblem);
   const archivedBank=await request(`/admin/problem-banks/${privateBank}`,'PATCH',{archived:true},admin);
   assert.equal(archivedBank.status,200,JSON.stringify(archivedBank.data));
   assert.equal((await request(`/problems/${privateProblem}?versionId=${privateVersion}`,'GET',undefined,student)).status,200,'published assignment keeps its exact version after a private bank is archived');
   assert.equal((await request(`/admin/problems/${privateProblem}`,'PATCH',{archived:false},admin)).data.error.code,'BANK_ARCHIVED');
   const restoredBank=await request(`/admin/problem-banks/${privateBank}`,'PATCH',{archived:false},admin);
   assert.equal(restoredBank.status,200);
   assert.equal((await request('/admin/problem-banks','GET',undefined,admin)).data.items.find(b=>b.id===privateBank).archivedAt,null);
  } finally {
   if(server)await new Promise(resolve=>server.close(resolve));
   await pool.end();
   await manager.query(`DROP SCHEMA IF EXISTS ${schema} CASCADE`);
   await manager.end();
  }
 });
