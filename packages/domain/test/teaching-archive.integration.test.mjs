import test from 'node:test';
import assert from 'node:assert/strict';
import http from 'node:http';
import { randomBytes, randomUUID } from 'node:crypto';
import { createPool } from '../src/db.mjs';
import { migrate } from '../src/migrate.mjs';
import { bootstrap } from '../src/bootstrap.mjs';
import { createApp, loadConfig } from '../src/app.mjs';

test('class, course, assignment and timed archives preserve records and enforce activity boundaries',
  {skip:!process.env.TEST_DATABASE_URL,timeout:60000},async()=>{
    const manager=createPool(process.env.TEST_DATABASE_URL);
    const schema=`archive_${randomBytes(6).toString('hex')}`;
    await manager.query(`CREATE SCHEMA ${schema}`);
    const url=new URL(process.env.TEST_DATABASE_URL);
    url.searchParams.set('options',`-csearch_path=${schema}`);
    const pool=createPool(url.href);
    let server;
    try{
      await migrate(pool);
      const password=`test-${randomUUID()}-Archive`;
      await bootstrap(pool,{name:'Admin',number:'ARC-A',username:'archive-admin',password});
      server=http.createServer(await createApp(pool,loadConfig({SESSION_SECRET:randomBytes(48).toString('hex'),APP_ORIGIN:'http://archive.test',COOKIE_SECURE:'false'})));
      await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
      const base=`http://127.0.0.1:${server.address().port}/api/v1`;
      function client(){let cookie='',csrf='';return async(path,body,method=body===undefined?'GET':'POST',status=200)=>{
        const response=await fetch(base+path,{method,headers:{Origin:'http://archive.test',...(cookie?{Cookie:cookie,'X-CSRF-Token':csrf}:{}),...(body===undefined?{}:{'Content-Type':'application/json'})},...(body===undefined?{}:{body:JSON.stringify(body)})});
        const data=await response.json();
        assert.equal(response.status,status,`${method} ${path}: ${JSON.stringify(data)}`);
        if(response.headers.get('set-cookie'))cookie=response.headers.get('set-cookie').split(';')[0];
        if(data.csrfToken)csrf=data.csrfToken;
        return data;
      };}
      const admin=client(),teacher=client(),outsider=client(),student=client();
      await admin('/auth/login',{username:'archive-admin',password});
      const identities={};
      for(const [kind,api] of [['teacher',teacher],['student',student],['teacher',outsider]]){
        const number=`ARC-${kind}-${Object.keys(identities).length}`;
        const created=await admin('/people',{kind,number,name:number},'POST',201);
        identities[number]=created.person;
        await api('/auth/register',{kind,number,name:number,activationCode:created.activationCode,username:number.toLowerCase(),password},'POST',201);
      }
      const owner=identities['ARC-teacher-0'];
      const learner=identities['ARC-student-1'];
      const cls=await admin('/classes',{name:'Archive class',teacherIds:[owner.id],studentIds:[learner.id]},'POST',201);
      const course=await teacher('/learning-paths',{title:'Archive course'},'POST',201);
      const chapter=await teacher(`/learning-paths/${course.id}/chapters`,{title:'Lesson',content:'Lesson content'},'POST',201);
      await teacher(`/learning-paths/${course.id}/publish`,{});
      const problem=await teacher('/problems',{title:'Archive fixture',mode:'stdio',statement:'Print one',samples:[{input:'',expected:'1'}],tests:[{input:'',expected:'1',weight:100}],referenceCode:'print(1)',starterCode:''},'POST',201);
      await pool.query("UPDATE problem_versions SET validation_status='AC' WHERE id=$1",[problem.versionId]);
      await teacher(`/problems/${problem.id}/publish`,{versionId:problem.versionId});
      const assignment=await teacher('/assignments',{title:'Archive assignment',classId:cls.id,coursePathId:course.id,dueAt:new Date(Date.now()+3600000).toISOString(),problems:[{problemId:problem.id,points:100}],participants:[learner.id],state:'Published'},'POST',201);
      const practice=await teacher('/timed-practices',{title:'Archive practice',classId:cls.id,startsAt:new Date(Date.now()+3600000).toISOString(),endsAt:new Date(Date.now()+7200000).toISOString(),durationMinutes:30,problems:[{problemId:problem.id,versionId:problem.versionId,points:100}],participants:[learner.id]},'POST',201);
      await teacher(`/timed-practices/${practice.id}/publish`,{},'POST');
      const draftPractice=await teacher('/timed-practices',{title:'Private draft',classId:cls.id,startsAt:new Date(Date.now()+3600000).toISOString(),endsAt:new Date(Date.now()+7200000).toISOString(),durationMinutes:30,problems:[{problemId:problem.id,versionId:problem.versionId,points:100}],participants:[learner.id]},'POST',201);
      const submission=await student('/submissions',{kind:'submit',language:'python',problemId:problem.id,versionId:problem.versionId,assignmentId:assignment.id,code:'print(1)',idempotencyKey:randomUUID()},'POST',201);
      await pool.query("UPDATE submissions SET status='AC',score=100,passed=1,total=1 WHERE id=$1",[submission.id.slice(3)]);
      await outsider(`/assignments/${assignment.id}/archive`,{},'POST',403);
      await student(`/classes/${cls.id}/archive`,{},'POST',403);
      await teacher(`/assignments/${assignment.id}/archive`,{},'POST',409);
      await teacher(`/learning-paths/${course.id}`,{archived:true},'PATCH',409);
      await teacher(`/classes/${cls.id}/archive`,{},'POST',409);
      await pool.query("UPDATE assignments SET due_at=clock_timestamp()-interval '1 minute' WHERE id=$1",[assignment.id]);
      await teacher(`/assignments/${assignment.id}/archive`,{},'POST');
      assert.equal((await teacher('/assignments')).items.some(x=>x.id===assignment.id),false);
      assert.equal((await teacher('/assignments?archived=true')).items.find(x=>x.id===assignment.id).archived,true);
      assert.equal((await student('/assignments?archived=true')).items.find(x=>x.id===assignment.id).archived,true);
      assert.equal((await student(`/assignments/${assignment.id}`)).id,assignment.id);
      await teacher(`/learning-paths/${course.id}`,{archived:true},'PATCH');
      assert.equal((await teacher('/learning-paths?archived=true')).items.find(x=>x.id===course.id).archived,true);
      assert.equal((await teacher(`/learning-paths/${course.id}`)).chapters.length,1);
      await student(`/learning-paths/${course.id}`,undefined,'GET',404);
      await outsider(`/learning-paths/${course.id}`,undefined,'GET',404);
      await teacher(`/learning-paths/${course.id}/publish`,{},'POST',404);
      await teacher(`/learning-paths/${course.id}`,{title:'Cannot edit archived'},'PATCH',404);
      await student('/learning-paths?archived=true',undefined,'GET',403);
      await teacher(`/timed-practices/${practice.id}/end`,{reason:'Archive regression close'},'POST');
      await teacher(`/timed-practices/${practice.id}/results`,{},'POST');
      await teacher(`/timed-practices/${practice.id}/archive`,{},'POST');
      assert.equal((await teacher('/timed-practices?archived=true')).items.find(x=>x.id===practice.id).status,'Archived');
      assert.equal((await student('/timed-practices?archived=true')).items.find(x=>x.id===practice.id).status,'Archived');
      assert.equal((await student(`/timed-practices/${practice.id}`)).id,practice.id);
      await teacher(`/timed-practices/${draftPractice.id}/archive`,{},'POST');
      assert.equal((await student('/timed-practices?archived=true')).items.some(x=>x.id===draftPractice.id),false);
      await student(`/timed-practices/${draftPractice.id}`,undefined,'GET',404);
      await teacher(`/classes/${cls.id}/archive`,{},'POST');
      assert.equal((await teacher('/classes?archived=true')).items.find(x=>x.id===cls.id).archived,true);
      assert.equal((await teacher(`/submissions/${submission.id}`)).id,submission.id);
      assert.equal((await teacher(`/submissions?assignmentId=${assignment.id}`)).items.some(x=>x.id===submission.id),true);
      await teacher(`/submissions/${submission.id}/rejudge`,{reason:'Archived history must remain read only'},'POST',403);
      await outsider(`/submissions/${submission.id}`,undefined,'GET',403);
      await student('/submissions',{kind:'samples',language:'python',problemId:problem.id,versionId:problem.versionId,assignmentId:assignment.id,code:'print(1)',idempotencyKey:randomUUID()},'POST',409);
      await student('/submissions',{kind:'correction',language:'python',problemId:problem.id,versionId:problem.versionId,assignmentId:assignment.id,originalSubmissionId:submission.id,code:'print(1)',idempotencyKey:randomUUID()},'POST',409);
      const report=await teacher(`/reports?classId=${cls.id}`);
      assert.equal(report.classes.find(x=>x.id===cls.id).archived,true);
      assert.equal(report.assignments.some(x=>x.id===assignment.id),true);
      assert.equal(report.timedPractices.some(x=>x.id===draftPractice.id),false);
      assert.equal(report.students.some(x=>x.identityId===learner.id),true);
      await pool.query('UPDATE problems SET archived_at=clock_timestamp() WHERE id=$1',[problem.id]);
      assert.equal((await teacher(`/problems/${problem.id}?versionId=${problem.versionId}`)).versionId,problem.versionId);
      assert.equal((await student(`/problems/${problem.id}?versionId=${problem.versionId}`)).versionId,problem.versionId);
      await outsider(`/problems/${problem.id}?versionId=${problem.versionId}`,undefined,'GET',404);
      await pool.query('UPDATE problems SET archived_at=NULL WHERE id=$1',[problem.id]);
      assert.equal((await pool.query('SELECT count(*)::int n FROM class_members WHERE class_id=$1',[cls.id])).rows[0].n,1);
      assert.equal((await pool.query('SELECT count(*)::int n FROM assignment_participants WHERE assignment_id=$1',[assignment.id])).rows[0].n,1);
      await teacher(`/assignments/${assignment.id}/restore`,{},'POST',409);
      await teacher(`/timed-practices/${practice.id}/restore`,{},'POST',409);
      await teacher(`/classes/${cls.id}/restore`,{},'POST');
      await pool.query('UPDATE problems SET archived_at=clock_timestamp() WHERE id=$1',[problem.id]);
      await teacher(`/assignments/${assignment.id}/restore`,{},'POST',409);
      await teacher(`/timed-practices/${draftPractice.id}/restore`,{},'POST');
      await teacher(`/timed-practices/${draftPractice.id}/publish`,{},'POST',409);
      await pool.query('UPDATE problems SET archived_at=NULL WHERE id=$1',[problem.id]);
      await teacher(`/assignments/${assignment.id}/restore`,{},'POST');
      await teacher(`/timed-practices/${practice.id}/restore`,{},'POST');
      await pool.query('INSERT INTO chapter_problems(chapter_id,problem_id,version_id,position) VALUES($1,$2,$3,0)',[chapter.id,problem.id,problem.versionId]);
      await teacher(`/learning-paths/${course.id}/restore`,{},'POST',409);
      await pool.query('DELETE FROM chapter_problems WHERE chapter_id=$1 AND problem_id=$2',[chapter.id,problem.id]);
      await teacher(`/learning-paths/${course.id}/restore`,{},'POST');
      assert.equal((await teacher('/classes')).items.some(x=>x.id===cls.id),true);
      assert.equal((await teacher('/assignments')).items.some(x=>x.id===assignment.id),true);
      assert.equal((await teacher('/timed-practices')).items.find(x=>x.id===practice.id).status,'ResultsPublished');
      assert.equal((await teacher('/learning-paths')).items.some(x=>x.id===course.id),true);
    }finally{
      if(server)await new Promise(resolve=>server.close(resolve));
      await pool.end();
      await manager.query(`DROP SCHEMA ${schema} CASCADE`);
      await manager.end();
    }
  });
